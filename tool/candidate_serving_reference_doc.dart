/// Path of the generated serving reference document.
const String candidateServingReferenceDocPath =
    'docs/CANDIDATE_SERVING_REFERENCE.md';

/// The built-in catalogs, in display order.
Map<String, List<FoodItem>> builtInServingCatalogs() => {
  'Built-in CIQUAL catalog (`buildP0FoodCatalog`)': buildP0FoodCatalog(),
  'USDA SR Legacy reference catalog (`buildReferenceFoodCatalog`)':
      buildReferenceFoodCatalog(),
  'Seed catalogs (`SeedCatalogImporter`, `RegionalSeedCatalogImporter`)': [
    ...const SeedCatalogImporter().importSeedCatalog().projectedFoods,
    ...const RegionalSeedCatalogImporter()
        .importRegionalSeedCatalog()
        .projectedFoods,
  ],
};

/// Renders `docs/CANDIDATE_SERVING_REFERENCE.md` from the production
/// reference-amount table, category assignments and serving resolver.
String buildCandidateServingReferenceDoc() {
  final out = StringBuffer()
    ..writeln('# Candidate serving reference')
    ..writeln()
    ..writeln(
      'Generated by `dart run tool/generate_candidate_serving_reference_doc.dart` '
      'from `lib/core/constants/food_serving_reference_amounts.dart`, '
      '`lib/core/constants/food_serving_reference_assignments.dart` and '
      '`lib/domain/usecases/food_serving_reference_resolver.dart`. '
      '`test/candidate_serving_reference_doc_test.dart` fails when it is '
      'stale. Do not edit by hand.',
    )
    ..writeln()
    ..writeln(
      'Next-meal candidates are evaluated at a reference serving instead of '
      'per 100 g (see `docs/CONFLICT_ENGINE_MODEL.md` §18a). A serving is a '
      'portion reported by the food\'s source record (`source_portion`) or the '
      'reference amount for its product category (`category_default`); '
      'otherwise values stay per 100 g and are labelled "serving unknown" '
      '(`none`). Servings only make foods comparable. They are not portion '
      'advice, and this educational prototype claims no labeling compliance.',
    )
    ..writeln()
    ..writeln('## Reference amounts')
    ..writeln()
    ..writeln(
      'FDA 21 CFR 101.12(b) Table 2 (reference amounts customarily consumed, '
      'as amended at 81 FR 34000, 27 May 2016) and, for meat and poultry '
      'cuts, USDA FSIS 9 CFR 317.312(b) and 9 CFR 381.412(b). Volume amounts '
      'use the household measures of 21 CFR 101.9(b)(5)(viii) and are never '
      'converted to grams without the food\'s own household-measure weight. '
      'Wording is abridged.',
    )
    ..writeln()
    ..writeln('| Category | Product category | Reference amount | Source |')
    ..writeln('| --- | --- | --- | --- |');
  for (final category in foodServingReferenceCategories) {
    out.writeln(
      '| `${category.id}` | ${_cell(category.productCategory)} | '
      '${_cell(category.statedAmount)} | ${category.citation} |',
    );
  }

  final catalogs = builtInServingCatalogs();
  final resolved = {
    for (final entry in catalogs.entries)
      entry.key: [
        for (final food in entry.value) (food, foodServingReferenceFor(food)),
      ],
  };

  out
    ..writeln()
    ..writeln('## Outcome per built-in catalog')
    ..writeln()
    ..writeln('| Catalog | Foods | source_portion | category_default | none |')
    ..writeln('| --- | ---: | ---: | ---: | ---: |');
  for (final entry in resolved.entries) {
    int count(FoodServingBasis basis) =>
        entry.value.where((row) => row.$2.basis == basis).length;
    out.writeln(
      '| ${entry.key} | ${entry.value.length} | '
      '${count(FoodServingBasis.sourcePortion)} | '
      '${count(FoodServingBasis.categoryDefault)} | '
      '${count(FoodServingBasis.none)} |',
    );
  }
  out
    ..writeln()
    ..writeln(
      'Of the seed foods without a serving, 44 have no composition record at '
      'all, so every nutrient is unknown.',
    );

  for (final entry in resolved.entries) {
    out
      ..writeln()
      ..writeln('### ${entry.key}')
      ..writeln()
      ..writeln(
        '| Food id | Food | Basis | Serving | Rule | Portion or amount |',
      )
      ..writeln('| --- | --- | --- | ---: | --- | --- |');
    for (final (food, serving) in entry.value) {
      final grams = serving.grams;
      final detail = serving.basis == FoodServingBasis.none
          ? [
              serving.reason ?? '',
              if (serving.referenceCategoryId != null)
                '`${serving.referenceCategoryId}`',
            ].join(', ')
          : [
              serving.portionLabel ?? '',
              if (serving.referenceCategoryId != null)
                '`${serving.referenceCategoryId}`',
            ].join(', ');
      out.writeln(
        '| `${food.id}` | ${_cell(_displayName(food))} | '
        '${serving.basis.wireName} | '
        '${grams == null ? '—' : '${_formatGrams(grams)} g'} | '
        '${serving.ruleId} | ${_cell(detail)} |',
      );
    }
  }
  return out.toString();
}

String _displayName(FoodItem food) {
  final ascii = RegExp(r'^[\x20-\x7E]+$');
  for (final candidate in [food.name, ...food.aliases]) {
    if (ascii.hasMatch(candidate)) return candidate;
  }
  return food.name;
}

String _formatGrams(double grams) => grams == grams.roundToDouble()
    ? grams.toStringAsFixed(0)
    : grams.toStringAsFixed(2).replaceFirst(RegExp(r'0$'), '');

String _cell(String value) =>
    value.replaceAll('|', r'\|').replaceAll('\n', ' ');
