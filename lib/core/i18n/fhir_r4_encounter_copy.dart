  final separator = normalized.indexOf(RegExp('[-_]'));
  final family = separator < 0
      ? normalized
      : normalized.substring(0, separator);
  var value =
      kFhirR4EncounterCopy[family]?[key] ??
      kFhirR4EncounterCopy['en']![key] ??
      key;
